-- Additive domain tables; no legacy appointment/user/schedule changes.
CREATE TABLE IF NOT EXISTS spa_order (
 id BIGINT PRIMARY KEY,appointment_id BIGINT NOT NULL,order_no VARCHAR(32) NOT NULL,
 user_id BIGINT NOT NULL,amount DECIMAL(10,2) NOT NULL,
 status VARCHAR(32) NOT NULL DEFAULT 'WAITING_PAYMENT',payment_status VARCHAR(24) NOT NULL DEFAULT 'UNPAID',
 payment_channel VARCHAR(16) NULL,created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 expires_at DATETIME NOT NULL,updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY uk_order_appointment(appointment_id),UNIQUE KEY uk_order_no(order_no),KEY idx_order_user(user_id,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS spa_payment (
 id BIGINT PRIMARY KEY,order_id BIGINT NOT NULL,request_id VARCHAR(64) NOT NULL,
 kind VARCHAR(16) NOT NULL,channel VARCHAR(16) NOT NULL,amount DECIMAL(10,2) NOT NULL,
 status VARCHAR(24) NOT NULL,created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uk_payment_request(request_id),UNIQUE KEY uk_payment_order_kind(order_id,kind)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS spa_review (
 id BIGINT PRIMARY KEY,order_id BIGINT NOT NULL,user_id BIGINT NOT NULL,rating TINYINT NOT NULL,
 content VARCHAR(1000) NOT NULL,created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uk_review_order(order_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS spa_points_entry (
 id BIGINT PRIMARY KEY,user_id BIGINT NOT NULL,order_id BIGINT NOT NULL,points INT NOT NULL,
 reason VARCHAR(64) NOT NULL,created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uk_points_order(order_id),KEY idx_points_user(user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS spa_content (
 id BIGINT PRIMARY KEY,title VARCHAR(100) NOT NULL,description VARCHAR(1000) NOT NULL,
 image_url VARCHAR(500) NULL,sort_order INT NOT NULL DEFAULT 0,active TINYINT NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
